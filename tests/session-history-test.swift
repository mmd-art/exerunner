var checks = 0
@MainActor func check(_ value: @autoclosure () -> Bool, _ message: String) {
    if !value() { fatalError(message) }; checks += 1
}
@MainActor func rejected(_ message: String, _ action: () async throws -> Void) async {
    do { try await action(); fatalError("accepted: " + message) } catch { checks += 1 }
}
